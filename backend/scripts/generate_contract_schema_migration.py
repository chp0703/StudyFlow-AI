"""Đóng gói contracts/schemas/f1.schema.json thành SQL migration theo cách xác định.

Cách dùng: python backend/scripts/generate_contract_schema_migration.py [--check]
--check trả mã thoát khác 0 nếu migration đã lưu không còn đồng bộ.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "contracts" / "schemas" / "f1.schema.json"
TARGET = ROOT / "supabase" / "migrations" / "202611050012_f1_contract_schema.sql"


def render() -> str:
    defs = json.loads(SCHEMA.read_text(encoding="utf-8"))["$defs"]
    body = json.dumps(defs, ensure_ascii=False, separators=(",", ":"))
    assert "$json$" not in body, "schema text collides with the SQL quote tag"
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return f"""-- GENERATED by backend/scripts/generate_contract_schema_migration.py. Do not edit by hand.
-- Source: contracts/schemas/f1.schema.json ($defs, sha256 {digest}).
-- Shape validation only: ownership, versions and authorization stay explicit in the routines.
create extension if not exists pg_jsonschema with schema extensions;

-- shortcut: the bundle is rebuilt from a literal on every call; cache it if validation shows up in profiles.
create function app_private.contract_defs() returns jsonb
language sql immutable set search_path = '' as $fn$
select $json${body}$json$::jsonb
$fn$;

create function app_private.contract_schema_digest() returns text
language sql immutable set search_path = '' as $fn$
select '{digest}'
$fn$;

-- True when p_value satisfies the approved definition p_def (e.g. 'create_task_candidateArguments').
-- Unknown definitions and unsupported/unknown fields are rejected, never accepted.
create function app_private.matches_contract(p_def text, p_value jsonb) returns boolean
language plpgsql immutable set search_path = '' as $fn$
begin
    if not (app_private.contract_defs() ? p_def) then
        return false;
    end if;
    return extensions.jsonb_matches_schema(
        jsonb_build_object('$ref', '#/$defs/' || p_def, '$defs', app_private.contract_defs())::json,
        p_value);
end $fn$;

alter function app_private.contract_defs() owner to sf_rpc_owner;
alter function app_private.contract_schema_digest() owner to sf_rpc_owner;
alter function app_private.matches_contract(text, jsonb) owner to sf_rpc_owner;
revoke all on function app_private.contract_defs(), app_private.contract_schema_digest(),
    app_private.matches_contract(text, jsonb) from public, anon, authenticated;
"""


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_bytes().decode("utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is out of date; rerun without --check", file=sys.stderr)
            return 1
        print("contract schema migration is up to date")
        return 0
    TARGET.write_bytes(text.encode("utf-8"))
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
